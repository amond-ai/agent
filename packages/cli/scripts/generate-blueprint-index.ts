#!/usr/bin/env bun
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { buildBlueprintIndex } from '../src/lib/blueprint-index.ts'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '../../..')
const blueprintsDir = join(repoRoot, 'blueprints')
const outFile = join(here, '../src/generated/blueprints.ts')

async function main() {
  // A repository without a `blueprints/` directory ships no bundled content: write an empty index.
  const entries = await readdir(blueprintsDir).catch((err: NodeJS.ErrnoException) => {
    if (err.code === 'ENOENT') {
      return []
    }
    throw err
  })
  const allFiles = entries
    .filter(file => file.endsWith('.md') && file !== 'README.md')
    .sort()

  const files = await Promise.all(
    allFiles.map(async file => ({ file, source: await readFile(join(blueprintsDir, file), 'utf-8') })),
  )
  const { blueprints, kindRoots } = buildBlueprintIndex(files)

  const banner = `// AUTO-GENERATED by scripts/generate-blueprint-index.ts. Do not edit by hand.\n`
  const blueprintsLiteral = blueprints
    .map(
      blueprint =>
        `\t{ slug: ${JSON.stringify(blueprint.slug)}, kind: ${JSON.stringify(blueprint.kind)}, version: ${blueprint.version}, website: ${JSON.stringify(blueprint.website)}, aliases: ${JSON.stringify(blueprint.aliases)} },`,
    )
    .join('\n')
  const rootsLiteral = kindRoots
    .map(root => `\t{ kind: ${JSON.stringify(root.kind)}, version: ${root.version} },`)
    .join('\n')
  const out
    = `${banner
    }export const BLUEPRINTS: readonly { readonly slug: string; readonly kind: string; readonly version: number; readonly website: string; readonly aliases: readonly string[] }[] = [\n${blueprintsLiteral}\n];\n\n`
    + `export const KIND_ROOTS: readonly { readonly kind: string; readonly version: number }[] = [\n${rootsLiteral}\n];\n`

  await mkdir(dirname(outFile), { recursive: true })
  await writeFile(outFile, out, 'utf-8')
  console.error(
    `[blueprints] wrote ${outFile} (${blueprints.length} blueprints, ${kindRoots.length} kind roots)`,
  )
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : String(err))
  process.exit(1)
})
